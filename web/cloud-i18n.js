export function applyCloudMessages(appName = "Sayrove") {
  const name = typeof appName === "string" && appName.trim() ? appName.trim() : "Sayrove";
  for (const [locale, copy] of Object.entries(cloudMessages)) {
    Object.assign(messages[locale], copy, {
      appTitle: locale === "zh" && name === "Sayrove" ? "拾语" : name,
      authenticationRequired: copy.cloudSessionExpired,
      accountChanged: copy.cloudAccountChanged,
    });
  }
  return messages;
}

export function detectCloudLocale(languages = []) {
  const candidates = typeof languages === "string" ? [languages] : Array.isArray(languages) ? languages : [];
  for (const language of candidates) {
    if (typeof language !== "string") continue;
    const locale = language.trim().toLowerCase().replaceAll("_", "-").split("-")[0];
    if (Object.hasOwn(messages, locale)) return locale;
  }
  return "en";
}
